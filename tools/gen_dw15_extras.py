#!/usr/bin/env python3
"""Generate the Digimon World 1.5 editions of port features into dw.1_5.

"Guaranteed Item Drops (1.5)" -- the same edit as
dw.vanilla.trainer/guaranteed-drops (every species' dropChance -> 100), made
against 1.5's own Digimon table.

WHERE 1.5 KEEPS THE TABLE. 1.5 moved DIGIMON_DATA out of the stock image
(0x8012CEB4, 180 records; 1.5 reuses those bytes for other data). Its copy sits
in the boot staging block at 0x80139400, which the entry stub 0x80135000
copies to 0x801F4300 before jumping to the stock entry 0x800A4240. All 104
code references were retargeted there, among them battleStatsGainsAndDrops
(0x800ECEE8): `lbu s2, 0x801F4322 + type*0x34` then
`if (randomLimit(100) < s2) drop`. loadMMD accepts types below 384, so the
table has 384 slots; 225 are named (0-222, plus 240 and 300).

WHY THE PATCHES TARGET 0x801F4300, NOT THE EXE. main_exe writes are applied
when dispatch first reaches game.toml's entry_pc (0x800A4240), and under 1.5
that is AFTER the stub has copied the block -- a write to the staging copy
lands in BSS that crt0 then clears, and never reaches the live table
(measured: staging probe left 0x801F43BE at 50, live probe read 100). So each
guard is checked against, and each write lands in, the live copy the game
reads. Off 1.5 those addresses hold nothing, so the feature requires dw15
([[constraint]] requires_feature): the launcher turns 1.5 on with it, turning
1.5 off turns it off, and a state.toml naming it without 1.5 is refused before
boot instead of failing a guard.

"Evolution Unbound (1.5)" -- the same edit as dw.vanilla.gameplay/
evolution-unbound (same option and values, same rule: the six stat walls go to
max(1, v*pct/100); -1, 0 and the Rookie "1" flags stay), made against 1.5's
EVOLUTION_REQS. 1.5 keeps that table in a block it calls MODTBL.BIN (LBA
168481, 30720 B, "DTBL" header, 28-byte rows at +0x20, 384 slots; not in the
ISO9660 directory -- 1.5's guard loads it with readFile("MODTBL.BIN")), live
at 0x80089000 -- inside the TRN/TRN2 overlays' load range (0x80088800,
27604/21696 B). So 1.5 hooks getInTraining/Rookie/ChampionEvolutionTarget
(-> 0x801F9D40/9D70/9DA0 -> guard 0x801F9C00) to re-read MODTBL.BIN from disc
when its "DTBL"/"!END" markers are gone, counting reloads at 0x801F9ED0. At
boot the block comes from the exe instead: the stub copies the staged copy at
0x80142000 (exe file offset 0xB2000; the exe is at LBA 170423) to 0x80089000.

So each scaled wall is TWO disc_user writes and no main_exe write: one into
the staged copy inside 1.5's SLUS_010.32 (the boot copy), one into MODTBL.BIN
(every reload). Both files lie past the stock disc's end, in sectors the 1.5
delta owns; the runtime accepts writes there only from a feature that requires
dw15, and guards and applies them after the delta. A main_exe write would reach
the boot copy too, but the runtime re-applies every main_exe write, unguarded,
after a savestate load or a rewind: one taken during training would poke the
walls into the resident TRN overlay.

Rows covered: every row a chooser can read. calculateRequirementScore
(0x800E26B8) and the three choosers are the table's only readers -- all 16
lui/lo pairs into it sit in those four functions -- and its 3 callers pass a target from
EVOLUTION_PATHS (0x8008CF20 + (type-1)*24, to = int16[7] at +10). So the rows
are the union of every species' targets, minus placeholder rows whose walls
are 32767 (only 254: Phoenixmon's dead link, no Digimon record, and Ultimates
have no chooser). Rows no species targets are never read: 63-65 hold
non-requirement data, 66-179 and most of 223+ are 32767 placeholders, 216-219
are unused copies of Angemon's and Leomon's rows.

The generated block replaces everything after MARKER in the dw.1_5 manifest;
the hand-written dw15 feature above it is never touched.

  py -3.12 tools/gen_dw15_extras.py            # write
  py -3.12 tools/gen_dw15_extras.py --check    # verify only
  py -3.12 tools/gen_dw15_extras.py --patched <1.5.bin>
"""
import argparse
import os
import struct
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from check_dw15_compat import RELOCATED, Disc, Exe, sha256  # noqa: E402
from gen_gameplay_mods import EVO_CHOICES, STAT_FIELDS  # noqa: E402  same option

MANIFEST = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.1_5",
                        "1.0.0", "manifest.toml")
MARKER = "# ---- generated by tools/gen_dw15_extras.py below this line"

STUB = 0x80135000
STAGED_DIGIMON_DATA = 0x80139400          # in 1.5's exe image
LIVE_DIGIMON_DATA = 0x801F4300            # where the stub puts it
STRIDE, DROP_CHANCE = 0x34, 0x22
SLOTS = 384                               # loadMMD: slti at,s1,384

# Instructions that pin the layout above; any change means a new 1.5 build.
PINS = [
    (0x800A1F98, 0x2A210180, "loadMMD: slti at,s1,384"),
    (0x800ED2A0, 0x3C02801F, "battleStatsGainsAndDrops: lui v0,0x801F"),
    (0x800ED2A4, 0x24424322, "battleStatsGainsAndDrops: addiu v0,v0,0x4322"),
    (0x800ED2AC, 0x90520000, "battleStatsGainsAndDrops: lbu s2,0(v0)"),
    (0x800E26E4, 0x3C038009, "calculateRequirementScore: lui v1,0x8009"),
    (0x800E26E8, 0x24639020, "calculateRequirementScore: addiu v1,v1,0x9020"),
    (0x800E2BB4, 0x0807E75C, "getRookieEvolutionTarget: j 0x801F9D70"),
    (0x801F9D78, 0x0C07E700, "chooser trampoline: jal 0x801F9C00 (MODTBL guard)"),
    (0x800E2BEC, 0x3C028009, "getRookieEvolutionTarget: lui v0,0x8009"),
    (0x800E2BF4, 0x2442CF20, "getRookieEvolutionTarget: addiu v0,v0,0xCF20"),
    (0x800E2C04, 0x2452000A, "getRookieEvolutionTarget: addiu s2,v0,10"),
]

MODTBL_LBA, MODTBL_SIZE = 168481, 30720
MODTBL_LIVE, MODTBL_STAGED = 0x80089000, 0x80142000   # stub's third block
REQS, REQ_STRIDE = 0x20, 28                    # EVOLUTION_REQS 0x80089020
PATHS, PATH_STRIDE, PATH_TO = 0x3F20, 24, 10   # EVOLUTION_PATHS 0x8008CF20
END = 0x72B0                                   # "!END" at 0x800902B0
PLACEHOLDER = 0x7FFF


def stub_copies(exe):
    """Decode the stub's three lui/addiu src, lui/addiu dst, word-count copies."""
    def imm(a):
        return struct.unpack("<I", exe.at(a, 4))[0] & 0xFFFF

    def lui_addiu(a):
        lo = imm(a + 4)
        return ((imm(a) << 16) + (lo - 0x10000 if lo & 0x8000 else lo)) & 0xFFFFFFFF
    out = []
    for at in (STUB, STUB + 0x2C, STUB + 0x58):
        out.append((lui_addiu(at), lui_addiu(at + 8), imm(at + 16) * 4))
    return out


def collect(exe):
    problems = []
    if stub_copies(exe) != RELOCATED:
        problems.append("entry stub copies %s, expected %s"
                        % (stub_copies(exe), RELOCATED))
    for addr, want, what in PINS:
        got = struct.unpack("<I", exe.at(addr, 4))[0]
        if got != want:
            problems.append("0x%08X is %08X, expected %08X (%s)"
                            % (addr, got, want, what))
    src, dst, n = RELOCATED[0]
    if STAGED_DIGIMON_DATA - src + dst != LIVE_DIGIMON_DATA or \
            STAGED_DIGIMON_DATA + SLOTS * STRIDE > src + n:
        problems.append("DIGIMON_DATA is not inside the first copied block")

    named, drops = 0, []
    for i in range(SLOTS):
        rec = exe.at(STAGED_DIGIMON_DATA + i * STRIDE, STRIDE)
        chance = rec[DROP_CHANCE]
        # Nameless slots are all-zero in Test Build 1.3.1 (no model, chance 0),
        # and no map file places one. Cover one anyway if it ever holds a drop.
        if rec[0] == 0 and chance == 0:
            continue
        named += rec[0] != 0
        if chance > 100:
            problems.append("record %d dropChance is %d (>100)" % (i, chance))
        elif chance != 100:
            name = rec[:20].split(b"\0")[0].decode("ascii", "replace")
            drops.append((i, name, chance))
    return problems, named, drops


def collect_evo(disc, exe):
    """-> problems, skipped rows, [(row, name, [(field idx, wall), ...])], and
    the two disc_user bases of the table: 1.5's exe staged copy, MODTBL.BIN."""
    problems = []
    tbl = disc.user(MODTBL_LBA * 2048, MODTBL_SIZE)
    if tbl[:4] != b"DTBL" or struct.unpack_from("<I", tbl, 4)[0] != MODTBL_SIZE \
            or tbl[END:END + 4] != b"!END":
        problems.append("MODTBL.BIN at LBA %d has no DTBL/!END markers" % MODTBL_LBA)
    if tbl != exe.at(MODTBL_LIVE, MODTBL_SIZE):
        problems.append("MODTBL.BIN differs from the exe's boot copy")
    bases = (disc.files["/SLUS_010.32"][0] * 2048 + MODTBL_STAGED - exe.t_addr
             + 0x800, MODTBL_LBA * 2048)
    if disc.user(bases[0], MODTBL_SIZE) != tbl:
        problems.append("SLUS_010.32 at 0x%08X is not MODTBL.BIN" % MODTBL_STAGED)

    targets = set()
    for typ in range(1, SLOTS):
        at = PATHS + (typ - 1) * PATH_STRIDE + PATH_TO
        targets.update(t for t in struct.unpack_from("<7h", tbl, at) if t != -1)
    rows, skipped = [], []
    for t in sorted(targets):
        if not 0 <= t < SLOTS:
            problems.append("evolution target %d is outside the table" % t)
            continue
        rec = struct.unpack_from("<13h", tbl, REQS + t * REQ_STRIDE)
        walls = [(idx, rec[idx]) for _n, idx in STAT_FIELDS]
        if any(v == PLACEHOLDER for _i, v in walls):
            skipped.append(t)
            continue
        walls = [(i, v) for i, v in walls if v > 0]
        if walls:
            name = exe.at(LIVE_DIGIMON_DATA + t * STRIDE, 20).split(b"\0")[0]
            rows.append((t, name.decode("ascii", "replace"), walls))
    return problems, skipped, rows, bases


def render_evo(skipped, rows, bases):
    out = [
        "[[feature]]",
        'id = "dw15-evolution-unbound"',
        'name = "Evolution Unbound (1.5)"',
        'description = "Scales the six stat walls each evolution demands in '
        "Digimon World 1.5: HP, MP, Offense, Defense, Speed and Brain, for "
        "every evolution the game can choose, the new lines included. Care "
        "mistakes, weight, discipline, happiness and battle/tech counts are "
        "left alone, as in Evolution Unbound. Needs Digimon World 1.5 and "
        'turns it on."',
        'group = "Gameplay"',
        "default_enabled = false",
        "",
        "# Patches below sit in files only the 1.5 delta serves.",
        "[[constraint]]",
        'feature = "dw15-evolution-unbound"',
        'kind = "requires_feature"',
        'requires_feature = "dw15"',
        "",
        "[[option]]",
        'feature = "dw15-evolution-unbound"',
        'id = "walls"',
        'label = "Stat requirements"',
        'group = "Gameplay"',
        'type = "choice"',
        'default = "relaxed"',
        "",
    ]
    for value, _p, label, _d in EVO_CHOICES:
        out += ["[[option.choice]]", 'value = "%s"' % value,
                'label = "%s"' % label, ""]
    out += [
        "# EVOLUTION_REQS[row] stat walls (row*%d + 2 hp .. + 12 brain), each"
        % REQ_STRIDE,
        "# written in 1.5's SLUS_010.32 staged copy (boot; disc_user %d + 0x%X)"
        % (bases[0], REQS),
        "# and in MODTBL.BIN (reloads; disc_user %d + 0x%X)." % (bases[1], REQS),
        "# Placeholder target rows skipped (walls 32767): %s"
        % ", ".join(map(str, skipped)),
        "",
    ]
    for value, pct, _label, _d in EVO_CHOICES:
        if pct == 100:
            continue                       # vanilla = no write
        for t, name, walls in rows:
            changed = [(i, v, max(1, v * pct // 100)) for i, v in walls]
            changed = [c for c in changed if c[2] != c[1]]
            if changed:
                out.append("# %s: %d %s" % (value, t, name))
            for idx, old, new in changed:
                for base in bases:
                    off = base + REQS + t * REQ_STRIDE + idx * 2
                    assert off // 2048 == (off + 1) // 2048, off  # one sector
                    out += [
                        "[[patch]]",
                        'feature = "dw15-evolution-unbound"',
                        'target = "disc_user"',
                        "offset = %d" % off,
                        'expected = "%s"' % struct.pack("<h", old).hex(" "),
                        'replace = "%s"' % struct.pack("<h", new).hex(" "),
                        'when = { walls = "%s" }' % value,
                        "",
                    ]
    return "\n".join(out)


def render(named, drops):
    out = [
        MARKER,
        "# Do not hand-edit below: regenerate so every guard stays byte-exact",
        "# against 1.5's executable (checked against target_sha256 above).",
        "",
        "[[feature]]",
        'id = "dw15-guaranteed-drops"',
        'name = "Guaranteed Item Drops (1.5)"',
        'description = "Every Digimon you defeat in Digimon World 1.5 drops '
        "its item. The 1.5 edition of Guaranteed Item Drops: it raises the "
        "drop chance of all %d species in 1.5's own Digimon table, the new "
        'ones included, to certain. Needs Digimon World 1.5 and turns it on."'
        % named,
        'group = "Battle"',
        "default_enabled = false",
        "",
        "# Patches below sit in RAM that only 1.5's entry stub fills.",
        "[[constraint]]",
        'feature = "dw15-guaranteed-drops"',
        'kind = "requires_feature"',
        'requires_feature = "dw15"',
        "",
        "# DIGIMON_DATA[i].dropChance -> 100 in 1.5's live table",
        "# (0x%08X + i*0x%02X + 0x%02X; staged at 0x%08X in the exe)."
        % (LIVE_DIGIMON_DATA, STRIDE, DROP_CHANCE, STAGED_DIGIMON_DATA),
        "",
    ]
    for i, name, chance in drops:
        out += [
            "# %d %s (%d%%)" % (i, name, chance),
            "[[patch]]",
            'feature = "dw15-guaranteed-drops"',
            'target = "main_exe"',
            "address = 0x%08X" % (LIVE_DIGIMON_DATA + i * STRIDE + DROP_CHANCE),
            'expected = "%02x"' % chance,
            'replace = "64"',
            "",
        ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--patched", default=os.path.normpath(os.path.join(
        ROOT, "..", "dw15-release", "patched", "digimon_world_1_5_test1.bin")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    with open(MANIFEST, encoding="utf-8") as f:
        text = f.read()
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    want = tomllib.loads(head)["disc_delta"][0]["target_sha256"]
    if not os.path.exists(a.patched) or sha256(a.patched) != want:
        print("missing or wrong 1.5 image (want sha256 %s): %s" % (want, a.patched))
        return 2
    disc = Disc(a.patched)
    exe = Exe(disc.file("/SLUS_010.32"), RELOCATED)

    problems, named, drops = collect(exe)
    evo_problems, skipped, rows, bases = collect_evo(disc, exe)
    problems += evo_problems
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  " + p)
        return 1
    print("1.5 DIGIMON_DATA: %d named of %d slots, %d below 100%% drop chance"
          % (named, SLOTS, len(drops)))
    print("1.5 EVOLUTION_REQS: %d chooser targets have stat walls; placeholder "
          "targets skipped: %s" % (len(rows), skipped))
    new = head + render(named, drops) + "\n" + render_evo(skipped, rows, bases) + "\n"
    tomllib.loads(new)                     # never write a manifest that does not parse
    if a.check:
        print("--check: manifest is %s" % ("current" if new == text else "STALE"))
        return 0 if new == text else 1
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print("wrote %s" % MANIFEST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
