#!/usr/bin/env python3
"""Generate the "Digimon World - Gameplay" .psxmod manifest.

Two mods aimed at the systems that define this game rather than at generic
cheats. Both are choice-based so vanilla stays reachable.

  Tech Mastery
    Techniques are learned by winning battles and passing a hidden roll:
    battleMoveLearning does `if (random(100) < MOVE_LEARN_CHANCES[move][slot])`
    per candidate move, then picks one of the winners. The table holds values
    like 45/35/25, so most battles teach nothing and players grind. The 100 is
    a single immediate in the delay slot of the `jal random`, so lowering it
    raises every move's odds proportionally -- and at 1, random(1) is always 0,
    so any move with a nonzero chance is learned whenever it is a candidate.
    This does NOT let a Digimon learn moves it could never learn: the candidate
    list is still filtered by species and slot beforehand.

  Evolution Unbound
    EVO_REQ_DATA holds, per evolution target, the stat walls you must clear.
    They are the game's most opaque system and its biggest grind. This scales
    the six pure stat thresholds -- HP, MP, Offense, Defense, Speed, Brain --
    and nothing else. Deliberately untouched: care mistakes, weight,
    discipline, happiness, battle and tech counts. Weight in particular is an
    exact target rather than a floor, and scaling it would make evolutions
    unreachable rather than easier. A -1 means "not required" and is preserved
    exactly.

Every value is read from our own extracted executable, so Vice's changes are
respected rather than assumed away.

  python tools/gen_gameplay_mods.py            # write the manifest
  python tools/gen_gameplay_mods.py --check    # verify only
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXE = os.path.normpath(os.path.join(HERE, "..", "..", "game-vanilla", "extracted",
                                    "SLUS_010.32"))
LOAD_ADDR = 0x80090800
HDR = 0x800

PKG_ID = "dw.vanilla.gameplay"
PKG_VER = "1.0.0"
GAME_ID = "SLUS-01032"

# battleMoveLearning @0x800ED3B4: delay slot of `jal random` -> addiu $a0,$zero,100
TECH_SITE = 0x800ED528
TECH_STOCK_WORD = 0x24040064          # addiu $a0, $zero, 100
TECH_CHOICES = [
    ("normal", 100, "Normal (vanilla)",
     "The stock roll. Most battles teach nothing."),
    ("boosted", 50, "Boosted (about 2x)",
     "Halves the roll, so every move's listed chance roughly doubles."),
    ("guaranteed", 1, "Guaranteed",
     "random(1) is always 0, so any move that is a valid candidate for your "
     "Digimon is learned. Species and slot filtering still applies."),
]

# EVO_REQ_DATA[63], 28 bytes each: digimon, hp, mp, offense, defense, speed,
# brain, care, weight, discipline, happiness, battles, techs (int16), flags,
# padding. Only the six stat walls are scaled.
EVO_ADDR = 0x8012ABEC
EVO_COUNT = 63
EVO_STRIDE = 28
STAT_FIELDS = [("hp", 1), ("mp", 2), ("offense", 3),
               ("defense", 4), ("speed", 5), ("brain", 6)]
EVO_CHOICES = [
    ("vanilla", 100, "Vanilla", "Stock requirements."),
    ("relaxed", 75, "Relaxed (75%)", "Every stat wall drops by a quarter."),
    ("open", 50, "Open (50%)", "Every stat wall is halved."),
]


def file_off(v):
    return v - LOAD_ADDR + HDR


def hexs(b):
    return " ".join("%02x" % x for x in b)


def main():
    check_only = "--check" in sys.argv
    with open(EXE, "rb") as f:
        data = f.read()

    problems = []

    tech_cur = data[file_off(TECH_SITE):file_off(TECH_SITE) + 4]
    if struct.unpack("<I", tech_cur)[0] != TECH_STOCK_WORD:
        problems.append("tech site 0x%08X is %08X, expected %08X"
                        % (TECH_SITE, struct.unpack("<I", tech_cur)[0],
                           TECH_STOCK_WORD))

    # read the evolution table
    entries = []
    base = file_off(EVO_ADDR)
    for i in range(EVO_COUNT):
        rec = data[base + i * EVO_STRIDE: base + (i + 1) * EVO_STRIDE]
        vals = struct.unpack_from("<13h", rec, 0)
        entries.append(vals)
    req_count = sum(1 for v in entries for _n, idx in STAT_FIELDS if v[idx] > 0)

    print("Tech Mastery     : site 0x%08X  %s" % (TECH_SITE, hexs(tech_cur)))
    print("Evolution Unbound: %d entries, %d stat walls above zero"
          % (EVO_COUNT, req_count))
    sample = entries[1]
    print("    e.g. entry 1: digimon=%d hp=%d mp=%d off=%d def=%d spd=%d brain=%d"
          % (sample[0], sample[1], sample[2], sample[3], sample[4],
             sample[5], sample[6]))

    if problems:
        print("\nPROBLEMS:")
        for p in problems:
            print("  " + p)
        return 1
    if check_only:
        print("\n--check: nothing written")
        return 0

    out = [
        "# Digimon World - Gameplay. Generated by tools/gen_gameplay_mods.py;",
        "# regenerate rather than hand-editing so every guard stays byte-exact.",
        "",
        "format_version = 5",
        'id = "%s"' % PKG_ID,
        'version = "%s"' % PKG_VER,
        'name = "Gameplay"',
        'author = "DigimonWorldRecomp"',
        'description = "Retunes the two systems that define Digimon World: '
        'how techniques are learned, and how high the evolution stat walls '
        'are. Both default to vanilla."',
        'resolver = "declarative"',
        'save_compatibility = "shared"',
        "",
        "[[target]]",
        'game_id = "%s"' % GAME_ID,
        "",
        "[[feature]]",
        'id = "tech-mastery"',
        'name = "Tech Mastery"',
        'description = "Techniques are learned by winning battles and passing '
        'a hidden roll against a per-move chance table, so most fights teach '
        'nothing. This scales that roll. It cannot teach a Digimon a move it '
        'could never learn -- the candidate list is still filtered by species '
        'and slot first."',
        'group = "Gameplay"',
        "default_enabled = false",
        "",
        "[[option]]",
        'feature = "tech-mastery"',
        'id = "odds"',
        'label = "Learning odds"',
        'group = "Gameplay"',
        'type = "choice"',
        'default = "boosted"',
        "",
    ]
    for value, _n, label, desc in TECH_CHOICES:
        out += ["[[option.choice]]", 'value = "%s"' % value,
                'label = "%s"' % label, ""]

    out += [
        "[[feature]]",
        'id = "evolution-unbound"',
        'name = "Evolution Unbound"',
        'description = "Scales the six stat walls each evolution demands: HP, '
        'MP, Offense, Defense, Speed and Brain. Care mistakes, weight, '
        'discipline, happiness and battle/tech counts are deliberately left '
        'alone -- weight is an exact target rather than a floor, so scaling it '
        'would make evolutions unreachable instead of easier."',
        'group = "Gameplay"',
        "default_enabled = false",
        "",
        "[[option]]",
        'feature = "evolution-unbound"',
        'id = "walls"',
        'label = "Stat requirements"',
        'group = "Gameplay"',
        'type = "choice"',
        'default = "relaxed"',
        "",
    ]
    for value, _p, label, desc in EVO_CHOICES:
        out += ["[[option.choice]]", 'value = "%s"' % value,
                'label = "%s"' % label, ""]

    # --- patches ---------------------------------------------------------
    for value, imm, label, _d in TECH_CHOICES:
        if imm == 100:
            continue                       # vanilla = no write
        word = 0x24040000 | imm
        out += [
            "# battleMoveLearning: random(100) -> random(%d)  [%s]" % (imm, label),
            "[[patch]]",
            'feature = "tech-mastery"',
            'target = "main_exe"',
            "address = 0x%08X" % TECH_SITE,
            'expected = "%s"' % hexs(tech_cur),
            'replace = "%s"' % hexs(struct.pack("<I", word)),
            'when = { odds = "%s" }' % value,
            "",
        ]

    emitted = 0
    for value, pct, label, _d in EVO_CHOICES:
        if pct == 100:
            continue
        for i, vals in enumerate(entries):
            for fname, idx in STAT_FIELDS:
                cur = vals[idx]
                if cur <= 0:               # -1 = not required, 0 = nothing to scale
                    continue
                new = max(1, (cur * pct) // 100)
                if new == cur:
                    continue
                addr = EVO_ADDR + i * EVO_STRIDE + idx * 2
                out += [
                    "[[patch]]",
                    'feature = "evolution-unbound"',
                    'target = "main_exe"',
                    "address = 0x%08X" % addr,
                    'expected = "%s"' % hexs(struct.pack("<h", cur)),
                    'replace = "%s"' % hexs(struct.pack("<h", new)),
                    'when = { walls = "%s" }' % value,
                    "",
                ]
                emitted += 1

    print("    emitted %d evolution patches across %d non-vanilla levels"
          % (emitted, len(EVO_CHOICES) - 1))

    dest_dir = os.path.normpath(os.path.join(
        HERE, "..", "mods", "packages", PKG_ID, PKG_VER))
    os.makedirs(dest_dir, exist_ok=True)
    dest = os.path.join(dest_dir, "manifest.toml")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s" % dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
