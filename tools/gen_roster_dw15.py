#!/usr/bin/env python3
"""Expanded Roster on Digimon World 1.5: the roster-15 edition of dw.vanilla.roster/roster.

WHY THIS EXISTS. The stock roster grows eight type-indexed partner tables into an
enhancement arena and authors 51 enemy-only species into the headroom, plus
Machinedramon in the free slot 114. 1.5 already grew every one of those tables to
384 types and filled the rows for these 51 species with placeholders, so on 1.5
nothing is relocated: this writes the roster's rows into 1.5's own tables.

  table            1.5 address           index      written as
  EVO_REQ          0x80089020 (MODTBL)   [type]     disc_user, both copies
  EVO_GAINS        0x8008BA20 (MODTBL)   [type]     disc_user, both copies
  EVO_PATHS        0x8008CF20 (MODTBL)   [type-1]   disc_user, both copies
  RAISE_DATA       0x801FA01C            [type]     main_exe
  ITEM_TAKE        0x801FCA40            [type-1]   main_exe
  TRAINING_ANIM    0x8012ED14            [type]     main_exe
  TRN2_ANIM        0x8012F014            [type]     main_exe

The MODTBL block is re-read from disc whenever a training overlay has overwritten
it (docs/INTERNALS.md 4.4), so its rows go into both disc copies and never into
main_exe. Rows are the stock roster's: its authored requirement rows, and
everything else copied from the same donor species, from 1.5's tables.

RAISED FLAGS. 1.5's setDigimonRaised (0x801F0D40) banks species 63..179 at
trigger 0x262 + species, which for 63..107 lands on ids 1.5's own scripts use
(treasure chests, 0x28A..0x2CC, tools/scan_trigger_ids.py). Plain 1.5 never
raises those species; the roster would. So 63..113 move to 0x296 + species
(0x2D5..0x307), above every scripted id and clear of 1.5's only raisable species
in the 115..179 bank (none; Veemon, 114, keeps 0x2D4). The stock roster does this
with a function-replacement hook, but a hook on a function 1.5 rewrote does not
fire, so here it is two guarded patches on 1.5's own functions; the set function
grows into the padding after it.

NOT CARRIED OVER, and why:
  * Machinedramon: slot 114 is Veemon in 1.5. 51 species, not 52.
  * The battle-intro name glyphs: 1.5 still reads the stock 112-row table, so
    WaruSeadramon (112) and Meteormon (113) show garbage on the arena banner,
    as they do without the roster. Fixing that needs the arena plugin.
  * The evolution-chart cursor fix: 1.5 rewrote the chart.

The block replaces everything after MARKER in the dw.vanilla.roster manifest;
gen_roster_mod.py keeps it when it rewrites the part above.

  py -3.12 tools/gen_roster_dw15.py            # write
  py -3.12 tools/gen_roster_dw15.py --check    # verify only
"""
import argparse
import os
import struct
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from check_dw15_compat import RAM_BASE, RELOCATED, Disc, Exe, sha256  # noqa: E402
from gen_roster_mod import NEW_SPECIES  # noqa: E402  the same species, requirements and donors

MANIFEST = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.vanilla.roster", "1.0.0", "manifest.toml")
DW15_MANIFEST = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.1_5", "1.0.0", "manifest.toml")
MARKER = "# ---- generated by tools/gen_roster_dw15.py below this line"

DIGIMON_DATA, DD_STRIDE = 0x801F4300, 0x34
MODTBL, MODTBL_LBA, MODTBL_SIZE, MODTBL_STAGED = 0x80089000, 168481, 30720, 0x80142000
EVO_REQ, EVO_GAINS, EVO_PATHS = 0x80089020, 0x8008BA20, 0x8008CF20
RAISE, ITEM_TAKE, TRN_ANIM, TRN2_ANIM = 0x801FA01C, 0x801FCA40, 0x8012ED14, 0x8012F014
SET_RAISED, HAS_RAISED = 0x801F0D40, 0x801F9B80
ROSTER_BANK = 0x296                       # trigger = 0x296 + species: 63..113 -> 0x2D5..0x307

# 1.5's setDigimonRaised, rewritten: 63..113 go to the roster bank, everything
# else exactly as 1.5 had it. Runs into the padding (nops) after the function.
SET_NEW = [
    0x2C8100B4,   # D40 sltiu at,a0,180
    0x1020000D,   # D44 beq   at,zero,ret
    0x2C81003F,   # D48 sltiu at,a0,63
    0x14200005,   # D4C bne   at,zero,call
    0x20820200,   # D50 addi  v0,a0,0x200       (delay: < 63 stock)
    0x2C810072,   # D54 sltiu at,a0,114
    0x14200002,   # D58 bne   at,zero,call
    0x20820296,   # D5C addi  v0,a0,0x296       (delay: 63..113 the roster bank)
    0x20820262,   # D60 addi  v0,a0,0x262       (114..179 as 1.5)
    0x27BDFFE8,   # D64 call: addiu sp,sp,-24
    0xAFBF0010,   # D68 sw    ra,16(sp)
    0x0C041970,   # D6C jal   setTrigger 0x801065C0
    0x3044FFFF,   # D70 andi  a0,v0,0xFFFF
    0x8FBF0010,   # D74 lw    ra,16(sp)
    0x27BD0018,   # D78 addiu sp,sp,24
    0x03E00008,   # D7C ret: jr ra
    0x00000000,   # D80 nop
]
# 1.5's hasDigimonRaised: the trigger path now covers up to 113 (it read 112 and
# up from a bitmap 1.5's set never writes below 180), at the same bank.
HAS_EDIT = [(HAS_RAISED + 0x00, 0x2C810070, 0x2C810072),   # sltiu at,a0,112 -> 114
            (HAS_RAISED + 0x14, 0x20820262, 0x20820296)]   # addi v0,a0,0x262 -> 0x296
# Unchanged from the stock roster, and unchanged bytes on 1.5.
STOCK_WORDS = [
    (0x800A7378, 0x1020004F, 0x1000004F,
     "partnerWillRefuseItem: Giga Hand, Noble Mane and Metalbanana skip the level test"),
    (0x800EFAD4, 0x2A01003B, 0x2A010072,
     "recalculatePPandArena: Prosperity counts recruits up to type 113"),
]


def hexs(b):
    return " ".join("%02x" % x for x in b)


def words(ws):
    return b"".join(struct.pack("<I", w) for w in ws)


def build(disc, exe):
    problems, out = [], []
    ram = lambda a, n: bytes(exe.ram[a - RAM_BASE:a - RAM_BASE + n])
    tbl = disc.user(MODTBL_LBA * 2048, MODTBL_SIZE)
    slus = disc.files["/SLUS_010.32"][0] * 2048 + MODTBL_STAGED - exe.t_addr + 0x800
    if disc.user(slus, MODTBL_SIZE) != tbl:
        problems.append("the exe's MODTBL copy differs from MODTBL.BIN")
    mod = lambda a, n: tbl[a - MODTBL:a - MODTBL + n]
    name = lambda t: ram(DIGIMON_DATA + t * DD_STRIDE, 20).split(b"\0")[0].decode("ascii", "replace")
    level = lambda t: ram(DIGIMON_DATA + t * DD_STRIDE + 29, 1)[0]

    def exe_patch(why, addr, new):
        if ram(addr, len(new)) == new:        # a donor that is the species itself: nothing to write
            return
        out.extend(["# " + why, "[[patch]]", 'feature = "roster-15"', 'target = "main_exe"',
                    "address = 0x%08X" % addr, 'expected = "%s"' % hexs(ram(addr, len(new))),
                    'replace = "%s"' % hexs(new), ""])

    def mod_patch(why, addr, new):           # both copies, split at sector boundaries
        for base, copy in ((slus, "the exe's copy"), (MODTBL_LBA * 2048, "MODTBL.BIN")):
            off, data, i = base + addr - MODTBL, new, 0
            while i < len(data):
                n = min(len(data) - i, 2048 - (off + i) % 2048)
                if disc.user(off + i, n) == data[i:i + n]:
                    i += n
                    continue
                out.extend(["# %s (%s)" % (why, copy), "[[patch]]", 'feature = "roster-15"',
                            'target = "disc_user"', "offset = %d" % (off + i),
                            'expected = "%s"' % hexs(disc.user(off + i, n)),
                            'replace = "%s"' % hexs(data[i:i + n]), ""])
                i += n

    out += [MARKER, "# Do not hand-edit below: regenerate so every guard stays byte-exact against 1.5.", "",
            "[[feature]]", 'id = "roster-15"', 'name = "51 new raisable Digimon (1.5)"',
            'description = "The Expanded Roster on Digimon World 1.5: the same 51 Digimon, raisable, written into '
            '1.5\'s own tables. Machinedramon is left out: its slot is Veemon in 1.5. It runs by itself in place '
            'of the Expanded Roster while 1.5 is on."',
            'group = "Roster"', "default_enabled = false", "hidden = true",
            'edition_of = "dw.vanilla.roster/roster"', "",
            "# Only with 1.5 beneath it: its MODTBL writes go on sectors the 1.5 delta owns.",
            "[[requirement]]", 'feature = "roster-15"', 'package = "dw.1_5"', 'requires_feature = "dw15"', ""]

    paths = {}                                # source type -> its 7 targets, as written so far
    for spec in NEW_SPECIES:
        t, d = spec["type"], spec["raise_donor"]
        if name(t) != spec["name"] or level(t) != level(d):
            problems.append("type %d is %s level %d on 1.5; donor %s level %d"
                            % (t, name(t), level(t), name(d), level(d)))
            continue
        nm = spec["name"]
        mod_patch("%s: requirements" % nm, EVO_REQ + t * 28, struct.pack("<13hBB", *(spec["req"] + (0,))))
        gains = bytearray(mod(EVO_GAINS + spec["gains_donor"] * 14, 14))
        gains[12:14] = struct.pack("<h", t)
        mod_patch("%s: evolution gains (from %s)" % (nm, name(spec["gains_donor"])), EVO_GAINS + t * 14, bytes(gains))
        exe_patch("%s: raise data (from %s)" % (nm, name(d)), RAISE + t * 28, ram(RAISE + d * 28, 28))
        exe_patch("%s: item-take distance (from %s)" % (nm, name(d)), ITEM_TAKE + t - 1, ram(ITEM_TAKE + d - 1, 1))
        a = spec["anim_donor"]
        exe_patch("%s: Offense training animation (from %s)" % (nm, name(a)), TRN_ANIM + t * 2, ram(TRN_ANIM + a * 2, 2))
        exe_patch("%s: MP training animation (from %s)" % (nm, name(a)), TRN2_ANIM + t * 2, ram(TRN2_ANIM + a * 2, 2))
        for src_name, src in spec["src"]:
            if name(src) != src_name or level(src) != level(t) - 1:
                problems.append("%s cannot evolve into %s on 1.5" % (src_name, nm))
                continue
            row = paths.setdefault(src, list(struct.unpack_from("<7h", tbl, EVO_PATHS - MODTBL + (src - 1) * 24 + 10)))
            if t in row:
                continue
            if -1 not in row:
                problems.append("%s (type %d) has no free evolution slot on 1.5" % (src_name, src))
                continue
            row[row.index(-1)] = t
    for src, row in sorted(paths.items()):
        mod_patch("%s evolves into %s" % (name(src), ", ".join(name(x) for x in row if x != -1)),
                  EVO_PATHS + (src - 1) * 24 + 10, struct.pack("<7h", *row))

    old_set = ram(SET_RAISED, 4 * len(SET_NEW))
    if old_set[:0x34] != words([0x2C8100B4, 0x1020000A, 0x2C81003F, 0x14200002, 0x20820200, 0x20820262,
                                0x27BDFFE8, 0xAFBF0010, 0x0C041970, 0x3044FFFF, 0x8FBF0010, 0x27BD0018,
                                0x03E00008]) or any(old_set[0x34:]):
        problems.append("1.5's setDigimonRaised is not the function this rewrites")
    exe_patch("setDigimonRaised (1.5): species 63..113 to triggers 0x2D5..0x307", SET_RAISED, words(SET_NEW))
    for addr, old, new in HAS_EDIT:
        if ram(addr, 4) != struct.pack("<I", old):
            problems.append("1.5's hasDigimonRaised differs at 0x%08X" % addr)
        exe_patch("hasDigimonRaised (1.5): the same bank", addr, struct.pack("<I", new))
    for addr, old, new, why in STOCK_WORDS:
        if ram(addr, 4) != struct.pack("<I", old):
            problems.append("0x%08X differs on 1.5" % addr)
        exe_patch(why, addr, struct.pack("<I", new))
    return problems, "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--patched", default=os.path.normpath(os.path.join(
        ROOT, "..", "dw15-release", "patched", "digimon_world_1_5_test1.bin")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = open(MANIFEST, encoding="utf-8").read()
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    want = tomllib.loads(open(DW15_MANIFEST, encoding="utf-8").read())["disc_delta"][0]["target_sha256"]
    if not os.path.exists(a.patched) or sha256(a.patched) != want:
        print("missing or wrong 1.5 image (want sha256 %s): %s" % (want, a.patched))
        return 2
    disc = Disc(a.patched)
    problems, block = build(disc, Exe(disc.file("/SLUS_010.32"), RELOCATED))
    for p in problems:
        print("error: " + p)
    if problems:
        return 1
    new = head + block
    if a.check:
        ok = new == text
        print("--check: manifest is %s" % ("current" if ok else "STALE: run without --check"))
        return 0 if ok else 1
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("wrote %s" % MANIFEST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
