#!/usr/bin/env python3
"""Generate dw.vanilla.cheats -- the cheat list as launcher toggles.

WHY THIS IS GENERATED. Cheats live in `cheats.txt` and are applied per frame by
the runtime's GameShark engine. A mod manifest cannot express them: a `[[patch]]`
is a one-time guarded write to the executable image, while most of these codes
pin a value every frame, and many target heap addresses that do not exist in the
image at all.

So this does not copy the codes. It reads `cheats.txt`, emits one boolean
launcher option per cheat, and the plugin calls `psx_mod_cheat_set_enabled()`
with the cheat's NAME. The file stays the single source of truth for what each
code writes; the launcher only overrides the [x]. That is what makes drift
impossible in the direction that matters -- the manifest can never disagree with
the file about an address, because it does not contain one.

Regenerate whenever cheats.txt changes:

    py -3.12 tools/gen_cheats_mod.py

Writes mods/preloaded/packages/dw.vanilla.cheats/1.0.0/manifest.toml and
dw_cheats_data.inc. `--check` verifies they are current without writing, which
is what the release gate runs.
"""
import argparse
import io
import os
import re
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHEATS = os.path.join(ROOT, "cheats.txt")
PKG = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.vanilla.cheats", "1.0.0",
                   "manifest.toml")
INC = os.path.join(ROOT, "dw_cheats_data.inc")

# Section headers in cheats.txt map to launcher groups. The file's own comment
# rules divide it; this keeps the launcher list navigable instead of one wall of
# 57 checkboxes. Order matters: first match wins.
GROUPS = [
    (re.compile(r"\bmovies?\b", re.I), "Movies"),
    (re.compile(r"\bstats?\b", re.I), "Stats"),
    (re.compile(r"care state", re.I), "Care"),
    (re.compile(r"\btraining\b", re.I), "Training"),
    (re.compile(r"\bcity\b|prosperity", re.I), "City"),
    (re.compile(r"item|inventory", re.I), "Items"),
    (re.compile(r"battle|combat", re.I), "Battle"),
    (re.compile(r"new digimon|roster|partner", re.I), "Partner"),
    (re.compile(r"raise sim|clock|lifespan", re.I), "Raise sim"),
    (re.compile(r"medal|misc", re.I), "Misc"),
]
DEFAULT_GROUP = "Cheats"


def slug(name):
    """A manifest id: lowercase, [a-z0-9._-], never leading/trailing dot."""
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    s = s.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-.")
    s = re.sub(r"-{2,}", "-", s)
    return s[:96] or "cheat"


def parse(path):
    """(name, enabled, group, has_codes) per cheat, in file order."""
    out, group = [], DEFAULT_GROUP
    cur = None
    for raw in io.open(path, encoding="utf-8", errors="replace"):
        line = raw.rstrip("\n")
        stripped = line.strip()
        if stripped.startswith("#"):
            # a rule line like "# ---- training ----" changes the group
            m = re.match(r"^#\s*-{3,}\s*(.+?)\s*-{3,}\s*$", stripped)
            if m:
                head = m.group(1)
                group = DEFAULT_GROUP
                for rx, g in GROUPS:
                    if rx.search(head):
                        group = g
                        break
            continue
        m = re.match(r"^\[([ xX*])\]\s+(.*\S)\s*$", line)
        if m:
            cur = {"name": m.group(2), "on": m.group(1) not in " ",
                   "group": group, "codes": 0}
            out.append(cur)
            continue
        if re.match(r"^[0-9A-Fa-f]{8} [0-9A-Fa-f]{4}", line) and cur:
            cur["codes"] += 1
    return out


def render_manifest(cheats):
    q = chr(34)
    L = []
    A = L.append
    A("# GENERATED by tools/gen_cheats_mod.py from cheats.txt -- do not hand-edit.")
    A("#")
    A("# One boolean option per cheat. The option does NOT carry the code: the")
    A("# plugin calls psx_mod_cheat_set_enabled() with the cheat's name and the")
    A("# runtime's own engine applies whatever cheats.txt says that name writes.")
    A("# So this manifest can never disagree with the file about an address --")
    A("# it does not contain one. Regenerate after editing cheats.txt.")
    A("format_version = 5")
    A('id = "dw.vanilla.cheats"')
    A('version = "1.0.0"')
    A('name = "Cheats"')
    A('author = "DigimonWorldVanilla"')
    A('description = "The %d GameShark-style codes from cheats.txt, as toggles. '
      'Turning this feature on hands control of every cheat to the launcher; '
      'leave it off and cheats.txt keeps deciding, exactly as before."'
      % len(cheats))
    A('resolver = "declarative"')
    A('save_compatibility = "shared"')
    A("")
    A("[[target]]")
    A('game_id = "SLUS-01032"')
    A("")
    A("[[feature]]")
    A('id = "cheats"')
    A('name = "Cheats"')
    A('description = "Pick cheats here instead of editing cheats.txt. These are '
      'per-frame memory pokes like a real GameShark, so several write things the '
      'game saves to your memory card -- back it up first. Where a cheat and '
      'another mod touch the same thing, the cheat wins."')
    A('group = "Cheats"')
    A("default_enabled = false")
    A("")
    A("[[plugin]]")
    A('feature = "cheats"')
    A('id = "dw.cheats"')
    for c in cheats:
        A("")
        A("[[option]]")
        A('feature = "cheats"')
        A("id = %s%s%s" % (q, c["id"], q))
        A("label = %s%s%s" % (q, c["name"].replace(q, "'"), q))
        A("group = %s%s%s" % (q, c["group"], q))
        A('type = "boolean"')
        A('default = "%s"' % ("true" if c["on"] else "false"))
    return chr(10).join(L) + chr(10)


def render_inc(cheats):
    q = chr(34)
    L = []
    A = L.append
    A("/* GENERATED by tools/gen_cheats_mod.py from cheats.txt -- do not edit. */")
    A("")
    A("typedef struct { const char* option; const char* cheat; } DwCheatOption;")
    A("")
    A("static const DwCheatOption k_cheat_options[%d] = {" % len(cheats))
    for c in cheats:
        A("    { %s%s%s, %s%s%s }," % (q, c["id"], q, q,
                                       c["name"].replace(chr(92), chr(92) * 2)
                                       .replace(q, chr(92) + q), q))
    A("};")
    return chr(10).join(L) + chr(10)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the generated files match cheats.txt")
    a = ap.parse_args()

    cheats = parse(CHEATS)
    if not cheats:
        print("no cheats parsed from %s" % CHEATS, file=sys.stderr)
        return 2

    seen = {}
    for c in cheats:
        base = slug(c["name"])
        c["id"] = base if base not in seen else "%s-%d" % (base, seen[base])
        seen[base] = seen.get(base, 1) + 1

    nocode = [c["name"] for c in cheats if c["codes"] == 0]
    if nocode:
        print("cheats with no code lines (not offered): %s" % nocode,
              file=sys.stderr)
        cheats = [c for c in cheats if c["codes"] > 0]

    man, inc = render_manifest(cheats), render_inc(cheats)
    if a.check:
        bad = 0
        for path, want in ((PKG, man), (INC, inc)):
            have = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if have != want:
                print("STALE: %s does not match cheats.txt -- run "
                      "tools/gen_cheats_mod.py" % os.path.relpath(path, ROOT),
                      file=sys.stderr)
                bad = 1
        if not bad:
            print("OK: cheat manifest and data match cheats.txt (%d cheats)"
                  % len(cheats))
        return bad

    os.makedirs(os.path.dirname(PKG), exist_ok=True)
    io.open(PKG, "w", encoding="utf-8", newline="").write(man)
    io.open(INC, "w", encoding="utf-8", newline="").write(inc)
    print("wrote %s" % os.path.relpath(PKG, ROOT))
    print("wrote %s" % os.path.relpath(INC, ROOT))
    print("%d cheats, %d on by default, groups: %s"
          % (len(cheats), sum(1 for c in cheats if c["on"]),
             ", ".join(sorted({c["group"] for c in cheats}))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
