#!/usr/bin/env python3
"""New maps on Digimon World 1.5: the 1.5 editions glade-15 (dw.newmaps/glade) and factory-15 (dw.newmaps.factory).

WHY THIS EXISTS. 1.5 leaves everything the new maps need free -- map rows
239-243, MGEN17's sectors, DG script slot 118, MMM.DAT's unused area, the host
screens' warp slots -- but it moves things they write:

  * the file table: 1.5's stub copies it to 0x801F1000, so MGEN17's two
    entries are written there, not at 0x801214A8 (the factory has none: its
    names are served by dw_newmaps.c's lookupFileTable hook);
  * DG.SCN: 1.5 grew it and moved it past the stock end of the disc, so the
    glade's slot 118 is rewritten in 1.5's copy, as a guarded [[patch]] (the
    runtime refuses an [[overlay]] on a delta sector). The factory has no DG
    write: dw_newmaps.c's getScript hook serves its ids from MMM.DAT;
  * MAPHEAD.SCN's tail: 1.5 puts its own new sections there, so the glade's
    section goes after them and the factory's after the glade's. A section
    moved from base B to B' takes its row pointers along (a pointer in
    [B, B + len) gets + (B' - B)); the factory's sections are rebuilt at B'
    by gen_factory.py, since a guardian's IF jumps to an offset from
    MAPHEAD's start.

The factory also swaps one asset: afac4_15.dg is AFAC4's script with item
127 named as 1.5 names it (gen_factory.py builds it). Everything else is the
feature's own write, copied, with its guard checked against 1.5. The edition
is hidden and names its feature with edition_of, and its [[requirement]] on
dw.1_5/dw15 gates it: while 1.5 is on, ticking the map runs this instead
(psxrecomp/docs/MOD_PACKAGES.md, "Feature editions").

The block replaces everything after MARKER in the package's manifest;
gen_newmap.py and gen_factory.py keep it when they rewrite the part above.

  py -3.12 tools/gen_newmap_dw15.py [--package glade|factory]            # write
  py -3.12 tools/gen_newmap_dw15.py [--package glade|factory] --check    # verify only
"""
import argparse
import hashlib
import os
import struct
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from check_dw15_compat import RAM_BASE, RELOCATED, Disc, Exe, sha256  # noqa: E402

PKGS = os.path.join(ROOT, "mods", "preloaded", "packages")
DW15_MANIFEST = os.path.join(PKGS, "dw.1_5", "1.0.0", "manifest.toml")
DW15 = "dw.1_5/dw15"
MARKER = "# ---- generated by tools/gen_newmap_dw15.py below this line"

STOCK_FTE = 0x801214A8              # MGEN17.MAP, then .TFS, 12 bytes each (gen_newmap.py)
MH_TABLE = 0x466                    # MAPHEAD's row pointer table ends here; sections follow
MH_BUFFER = 0x61A8                  # MAPHEAD_SCRIPT_BUFFER size (docs/GAME.md 4.1)
DG_SLOT_STOCK = bytes.fromhex("0800fe000800fffffe00")


def factory_sections(base):
    """The factory's MAPHEAD sections rebuilt at offset `base` (a guardian's IF jumps to an offset from MAPHEAD's start)."""
    from gen_factory import mh_sections
    return b"".join(b for _, b in mh_sections(base))


def factory_checks(disc, exe):
    """1.5's DG.SCN table ends before the ids getScript serves, and the reward's items are what the paid line names."""
    from gen_factory import DW15_REWARD_NAME, ITEM_PARA, REWARD, REWARD_NAMES, SCRIPTS
    problems = []
    if struct.unpack_from("<I", disc.file("/SCN/DG.SCN"), 4 * 226)[0] != disc.files["/SCN/DG.SCN"][1] \
            or min(SCRIPTS) <= 226:
        problems.append("1.5's DG.SCN table[226] is not its size, or the factory's script ids %s are not past it" % (SCRIPTS,))
    name = lambda item: bytes(exe.ram[ITEM_PARA - RAM_BASE + 32 * item:][:20]).split(b"\0")[0].decode("ascii", "replace")
    want = [DW15_REWARD_NAME] + [n for _, n in REWARD_NAMES[1:]]
    for item, w in zip(REWARD, want):
        if name(item) != w:
            problems.append("item %d is %r on 1.5, not %r" % (item, name(item), w))
    return problems


# Per package: its manifest, the feature and its edition, the edition's plugin, the asset swaps, the DG slot whose
# overlay becomes a DG.SCN patch (glade), whose section the MAPHEAD tail follows (None: 1.5's own), how a moved
# section is rebuilt (None: its bytes hold no offsets), and package-specific checks.
SPECS = {
    "glade": dict(
        manifest=os.path.join(PKGS, "dw.newmaps", "1.0.0", "manifest.toml"), feature="glade", edition="glade-15",
        name="Hidden Glade (1.5)", plugin="dw.newmaps", swaps={}, dg_slot=118, mh_after=None, sections=None, checks=None,
        description="Hidden Glade on Digimon World 1.5: the same map and fight, written where 1.5 keeps the files it "
                    "moved. It runs by itself in place of Hidden Glade while 1.5 is on."),
    "factory": dict(
        manifest=os.path.join(PKGS, "dw.newmaps.factory", "1.0.0", "manifest.toml"), feature="factory",
        edition="factory-15", name="Abandoned Factory (1.5)", plugin="dw.newmaps.factory",
        swaps={"assets/afac4.dg": "assets/afac4_15.dg"}, dg_slot=None, mh_after=("glade", "glade-15"),
        sections=factory_sections, checks=factory_checks,
        description="The Abandoned Factory on Digimon World 1.5: the same four screens and fights, its MAPHEAD sections "
                    "after Hidden Glade's, and the boss's reward named as 1.5 names it. It runs by itself in place of "
                    "Abandoned Factory while 1.5 is on."),
}


def hexs(b):
    return " ".join("%02x" % x for x in b)


def mh_tail(m, feature, mh_base):
    """The feature's MAPHEAD section patch (past the pointer table): (offset in MAPHEAD, replace bytes), or None."""
    hits = [p for p in m.get("patch", []) if p["feature"] == feature and p["target"] == "disc_user"
            and mh_base + MH_TABLE <= p["offset"] < mh_base + MH_BUFFER]
    return (hits[0]["offset"] - mh_base, bytes.fromhex(hits[0]["replace"].replace(" ", ""))) if len(hits) == 1 else None


def build(disc, exe, head, pkg):
    spec = SPECS[pkg]
    m = tomllib.loads(head)
    feature, edition = spec["feature"], spec["edition"]
    problems = []
    patches = [p for p in m["patch"] if p["feature"] == feature]
    overlays = [o for o in m["overlay"] if o["feature"] == feature]
    stock = next(f for f in m["feature"] if f["id"] == feature)
    pkg_dir = os.path.dirname(spec["manifest"])
    mh_lba, _ = disc.files["/SCN/MAPHEAD.SCN"]
    dg_lba, _ = disc.files["/SCN/DG.SCN"]
    mh_base = mh_lba * 2048
    mh = disc.user(mh_base, MH_BUFFER)
    used = max(i for i, b in enumerate(mh) if b) + 1

    # MAPHEAD: the section moves from B to B', after 1.5's own sections or after another edition's.
    tail = mh_tail(m, feature, mh_base)
    if tail is None:
        problems.append("no %s MAPHEAD section in %s" % (feature, spec["manifest"]))
        return problems, ""
    B, sec = tail
    if spec["mh_after"] is None:
        new_b, after = used, "after 1.5's MAPHEAD sections (they end at %#x)" % used
    else:
        other, other_ed = spec["mh_after"]
        om = tomllib.loads(open(SPECS[other]["manifest"], encoding="utf-8").read())
        ot = mh_tail(om, other_ed, mh_base)
        if ot is None:
            problems.append("no %s MAPHEAD section in %s: run --package %s first" % (other_ed, SPECS[other]["manifest"], other))
            return problems, ""
        o_hi = ot[0] + len(ot[1])
        new_b, after = o_hi, "after %s's MAPHEAD section (it ends at %#x)" % (other_ed, o_hi)
        if new_b < used:                             # right after the other edition's: only 1.5's can overlap
            problems.append("%s's MAPHEAD sections at %#x overlap 1.5's (to %#x)" % (edition, new_b, used))
    new_b += new_b & 1                               # sections are halfword-aligned
    if new_b + len(sec) > MH_BUFFER:
        problems.append("no room for %s's MAPHEAD sections (%#x + %d > %#x)" % (edition, new_b, len(sec), MH_BUFFER))
    if spec["sections"]:                             # rebuilt at B': prove the rebuild matches the stock write first
        if spec["sections"](B) != sec:
            problems.append("%s's rebuilt MAPHEAD sections at %#x differ from the manifest's" % (feature, B))
        new_sec = spec["sections"](new_b)
    else:
        new_sec = sec
    if spec["checks"]:
        problems += spec["checks"](disc, exe)

    out = [MARKER,
           "# Do not hand-edit below: regenerate so every guard stays byte-exact against 1.5.",
           "",
           "[[feature]]", 'id = "%s"' % edition, 'name = "%s"' % spec["name"],
           'description = "%s"' % spec["description"],
           'group = "New maps"', "default_enabled = false", "hidden = true",
           'edition_of = "%s/%s"' % (m["id"], feature)]
    conflicts = [c for c in stock.get("conflicts", []) if c != DW15]
    if conflicts:
        out.append("conflicts = [%s]" % ", ".join('"%s"' % c for c in conflicts))
    out += ["",
            "# Only with 1.5 beneath it: its writes go on sectors the 1.5 delta owns.",
            "[[requirement]]", 'feature = "%s"' % edition, 'package = "dw.1_5"', 'requires_feature = "dw15"', "",
            "[[plugin]]", 'feature = "%s"' % edition, 'id = "%s"' % spec["plugin"], ""]
    swapped = set()
    for o in overlays:
        if spec["dg_slot"] is not None and o["file"].endswith(".dg"):   # DG moved: the slot is a patch in 1.5's copy
            slot = spec["dg_slot"]
            dg = open(os.path.join(pkg_dir, o["file"]), "rb").read()
            so, nxt = struct.unpack_from("<2I", disc.file("/SCN/DG.SCN"), 4 * slot)
            at = dg_lba * 2048 + so
            old = disc.user(at, len(dg))
            if not old.startswith(DG_SLOT_STOCK) or len(dg) > nxt - so:
                problems.append("1.5's DG slot %d is not the bare END the %s replaces" % (slot, feature))
            out += ["# DG script %d in 1.5's DG.SCN (LBA %d): the arrival END, plus the boss's section"
                    % (slot, dg_lba), "[[patch]]", 'feature = "%s"' % edition, 'target = "disc_user"',
                    "offset = %d" % at, 'expected = "%s"' % hexs(old), 'replace = "%s"' % hexs(dg), ""]
            continue
        f, digest = o["file"], o["sha256"]
        if f in spec["swaps"]:
            f = spec["swaps"][f]
            swapped.add(o["file"])
            digest = hashlib.sha256(open(os.path.join(pkg_dir, f), "rb").read()).hexdigest()
            out.append("# %s in place of %s" % (f, o["file"]))
        out += ["[[overlay]]", 'feature = "%s"' % edition, 'target = "%s"' % o["target"],
                "offset = %d" % o["offset"], 'file = "%s"' % f, 'sha256 = "%s"' % digest, ""]
    for f in set(spec["swaps"]) - swapped:
        problems.append("swap %s: %s has no such overlay" % (f, feature))
    for p in patches:
        exp = bytes.fromhex(p["expected"].replace(" ", ""))
        rep = bytes.fromhex(p["replace"].replace(" ", ""))
        why = "copied"
        if p["target"] == "main_exe":
            addr = p["address"]
            if STOCK_FTE <= addr < STOCK_FTE + 24:   # the file table entry: find 1.5's live copy of it
                hits = [a for a in range(0x801F0000, 0x801FD000, 4)
                        if exe.ram[a - RAM_BASE:a - RAM_BASE + len(exp)] == exp]
                if len(hits) != 1:
                    problems.append("file table entry %s is at %s on 1.5" % (hexs(exp), hits))
                    continue
                addr, why = hits[0], "1.5's file table at 0x801F1000"
            old = bytes(exe.ram[addr - RAM_BASE:addr - RAM_BASE + len(exp)])
            body = 'target = "main_exe"\naddress = 0x%08X' % addr
        else:
            off = p["offset"]
            if off == mh_base + B:                   # the section(s), moved to B'
                off, rep, exp, why = mh_base + new_b, new_sec, bytes(len(new_sec)), after
            elif mh_base <= off < mh_base + MH_TABLE and len(rep) == 2 \
                    and B <= struct.unpack("<H", rep)[0] < B + len(sec):
                rep = struct.pack("<H", struct.unpack("<H", rep)[0] + new_b - B)
                why = "row %d's section pointer" % struct.unpack_from("<H", mh, off - mh_base - 2)[0]
            old = disc.user(off, len(exp))
            body = 'target = "disc_user"\noffset = %d' % off
        # A copied or moved write must find on 1.5 what it found on the stock disc.
        if old != exp:
            problems.append("%s (%s): 1.5 has %s where the %s expects %s"
                            % (body.replace("\n", " "), why, hexs(old), feature, hexs(exp)))
        out += ["# " + why, "[[patch]]", 'feature = "%s"' % edition, body,
                'expected = "%s"' % hexs(old), 'replace = "%s"' % hexs(rep), ""]
    return problems, "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--package", choices=sorted(SPECS), default="glade")
    ap.add_argument("--patched", default=os.path.normpath(os.path.join(
        ROOT, "..", "dw15-release", "patched", "digimon_world_1_5_test1.bin")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    manifest = SPECS[a.package]["manifest"]
    text = open(manifest, encoding="utf-8").read()
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    want = tomllib.loads(open(DW15_MANIFEST, encoding="utf-8").read())["disc_delta"][0]["target_sha256"]
    if not os.path.exists(a.patched) or sha256(a.patched) != want:
        print("missing or wrong 1.5 image (want sha256 %s): %s" % (want, a.patched))
        return 2
    disc = Disc(a.patched)
    exe = Exe(disc.file("/SLUS_010.32"), RELOCATED)
    problems, block = build(disc, exe, head, a.package)
    for p in problems:
        print("error: " + p)
    if problems:
        return 1
    new = head + block
    if a.check:
        ok = new == text
        print("--check: manifest is %s" % ("current" if ok else "STALE: run without --check"))
        return 0 if ok else 1
    with open(manifest, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("wrote %s" % manifest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
