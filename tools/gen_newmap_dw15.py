#!/usr/bin/env python3
"""Hidden Glade on Digimon World 1.5: the glade-15 edition of dw.newmaps/glade.

WHY THIS EXISTS. 1.5 leaves everything the glade needs free -- map row 239,
MGEN17's sectors, DG script slot 118, MAYO03's warp slot 4 -- but it moves
three things the glade writes:

  * the file table: 1.5's stub copies it to 0x801F1000, so MGEN17's two
    entries are written there, not at 0x801214A8;
  * DG.SCN: 1.5 grew it and moved it past the stock end of the disc, so slot
    118 is rewritten in 1.5's copy, as a guarded [[patch]] (the runtime
    refuses an [[overlay]] on a delta sector);
  * MAPHEAD.SCN's tail: 1.5 puts its own new sections there, so the glade's
    section goes after them.

Everything else is the glade's own write, copied, with its guard checked
against 1.5. The edition is hidden and names glade with edition_of, and its
[[requirement]] on dw.1_5/dw15 gates it: while 1.5 is on, ticking Hidden Glade
runs this instead (psxrecomp/docs/MOD_PACKAGES.md, "Feature editions").

The block replaces everything after MARKER in the dw.newmaps manifest;
gen_newmap.py keeps it when it rewrites the part above.

  py -3.12 tools/gen_newmap_dw15.py            # write
  py -3.12 tools/gen_newmap_dw15.py --check    # verify only
"""
import argparse
import os
import struct
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from check_dw15_compat import RAM_BASE, RELOCATED, Disc, Exe, sha256  # noqa: E402

PKG = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.newmaps", "1.0.0")
MANIFEST = os.path.join(PKG, "manifest.toml")
DW15_MANIFEST = os.path.join(ROOT, "mods", "preloaded", "packages", "dw.1_5", "1.0.0", "manifest.toml")
MARKER = "# ---- generated by tools/gen_newmap_dw15.py below this line"

STOCK_FTE = 0x801214A8              # MGEN17.MAP, then .TFS, 12 bytes each (gen_newmap.py)
MH_BUFFER = 0x61A8                  # MAPHEAD_SCRIPT_BUFFER size (docs/GAME.md 4.1)
SCRIPT, DG_SLOT_STOCK = 118, bytes.fromhex("0800fe000800fffffe00")


def hexs(b):
    return " ".join("%02x" % x for x in b)


def build(disc, exe, head):
    m = tomllib.loads(head)
    problems = []
    patches = [p for p in m["patch"] if p["feature"] == "glade"]
    overlays = [o for o in m["overlay"] if o["feature"] == "glade"]
    mh_lba, mh_size = disc.files["/SCN/MAPHEAD.SCN"]
    dg_lba, _ = disc.files["/SCN/DG.SCN"]
    mh = disc.user(mh_lba * 2048, MH_BUFFER)
    used = max(i for i, b in enumerate(mh) if b) + 1
    mh_new = used + (used & 1)                       # sections are halfword-aligned

    out = [MARKER,
           "# Do not hand-edit below: regenerate so every guard stays byte-exact against 1.5.",
           "",
           "[[feature]]", 'id = "glade-15"', 'name = "Hidden Glade (1.5)"',
           'description = "Hidden Glade on Digimon World 1.5: the same map and fight, written where 1.5 keeps '
           'the files it moved. It runs by itself in place of Hidden Glade while 1.5 is on."',
           'group = "New maps"', "default_enabled = false", "hidden = true",
           'edition_of = "dw.newmaps/glade"', 'conflicts = ["dw.newmaps.spike/spike"]', "",
           "# Only with 1.5 beneath it: its writes go on sectors the 1.5 delta owns.",
           "[[requirement]]", 'feature = "glade-15"', 'package = "dw.1_5"', 'requires_feature = "dw15"', "",
           "[[plugin]]", 'feature = "glade-15"', 'id = "dw.newmaps"', ""]
    for o in overlays:
        out += ["[[overlay]]", 'feature = "glade-15"', 'target = "%s"' % o["target"],
                "offset = %d" % o["offset"], 'file = "%s"' % o["file"], 'sha256 = "%s"' % o["sha256"], ""]
        if o["file"].endswith(".dg"):
            out = out[:-7]                           # not this one: DG moved, it is a patch below
            dg = open(os.path.join(PKG, o["file"]), "rb").read()
            so = struct.unpack_from("<I", disc.file("/SCN/DG.SCN"), 4 * SCRIPT)[0]
            nxt = struct.unpack_from("<I", disc.file("/SCN/DG.SCN"), 4 * SCRIPT + 4)[0]
            at = dg_lba * 2048 + so
            old = disc.user(at, len(dg))
            if not old.startswith(DG_SLOT_STOCK) or len(dg) > nxt - so:
                problems.append("1.5's DG slot %d is not the bare END the glade replaces" % SCRIPT)
            out += ["# DG script %d in 1.5's DG.SCN (LBA %d): the arrival END, plus the boss's section"
                    % (SCRIPT, dg_lba), "[[patch]]", 'feature = "glade-15"', 'target = "disc_user"',
                    "offset = %d" % at, 'expected = "%s"' % hexs(old), 'replace = "%s"' % hexs(dg), ""]
    for p in patches:
        exp = bytes.fromhex(p["expected"].replace(" ", ""))
        rep = bytes.fromhex(p["replace"].replace(" ", ""))
        why = "copied"
        if p["target"] == "main_exe":
            addr = p["address"]
            if STOCK_FTE <= addr < STOCK_FTE + 24:   # the file table entry: find 1.5's live copy of it
                hits = [a for a in range(0x801F0000, 0x801FD000, 4)
                        if exe.ram[a - RAM_BASE:a - RAM_BASE + len(exp)] == exp]
                if len(hits) != 1:
                    problems.append("file table entry %s is at %s on 1.5" % (hexs(exp), hits))
                    continue
                addr, why = hits[0], "1.5's file table at 0x801F1000"
            old = bytes(exe.ram[addr - RAM_BASE:addr - RAM_BASE + len(exp)])
            body = 'target = "main_exe"\naddress = 0x%08X' % addr
        else:
            off = p["offset"]
            if off == mh_lba * 2048 + 0x6070:        # the glade's section, after 1.5's own
                if mh_new + len(rep) > MH_BUFFER:
                    problems.append("no room after 1.5's MAPHEAD sections (%#x + %d)" % (mh_new, len(rep)))
                off, why = mh_lba * 2048 + mh_new, "after 1.5's MAPHEAD sections (they end at %#x)" % used
            elif mh_lba * 2048 <= off < mh_lba * 2048 + 0x466 and rep == struct.pack("<H", 0x6070):
                rep, why = struct.pack("<H", mh_new), "row 239's section pointer"
            old = disc.user(off, len(exp))
            body = 'target = "disc_user"\noffset = %d' % off
        # A copied or moved write must find on 1.5 what it found on the stock disc.
        if old != exp:
            problems.append("%s (%s): 1.5 has %s where the glade expects %s"
                            % (body.replace("\n", " "), why, hexs(old), hexs(exp)))
        out += ["# " + why, "[[patch]]", 'feature = "glade-15"', body,
                'expected = "%s"' % hexs(old), 'replace = "%s"' % hexs(rep), ""]
    return problems, "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--patched", default=os.path.normpath(os.path.join(
        ROOT, "..", "dw15-release", "patched", "digimon_world_1_5_test1.bin")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = open(MANIFEST, encoding="utf-8").read()
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    want = tomllib.loads(open(DW15_MANIFEST, encoding="utf-8").read())["disc_delta"][0]["target_sha256"]
    if not os.path.exists(a.patched) or sha256(a.patched) != want:
        print("missing or wrong 1.5 image (want sha256 %s): %s" % (want, a.patched))
        return 2
    disc = Disc(a.patched)
    exe = Exe(disc.file("/SLUS_010.32"), RELOCATED)
    problems, block = build(disc, exe, head)
    for p in problems:
        print("error: " + p)
    if problems:
        return 1
    new = head + block
    if a.check:
        ok = new == text
        print("--check: manifest is %s" % ("current" if ok else "STALE: run without --check"))
        return 0 if ok else 1
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("wrote %s" % MANIFEST)
    return 0


if __name__ == "__main__":
    sys.exit(main())
